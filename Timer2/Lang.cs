        public const string PL = "pl";
        public const string EN = "en";

        public static string Current { get; private set; } = PL;

        public static event Action? Changed;

        public static string SystemDefault =>
            CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("pl", StringComparison.OrdinalIgnoreCase)
                ? PL : EN;

        public static void Set(string? code)
        {
            string c = string.Equals(code, EN, StringComparison.OrdinalIgnoreCase) ? EN : PL;
            if (c == Current) return;
            Current = c;
            Changed?.Invoke();
        }

        public static void SetQuiet(string? code) =>
            Current = string.Equals(code, EN, StringComparison.OrdinalIgnoreCase) ? EN : PL;

        public static string T(string key)
        {
            if (_texts.TryGetValue(key, out var pair))
                return Current == EN ? pair.en : pair.pl;
            return key;
        }

        public static string T(string key, params object[] args)
        {
            try { return string.Format(T(key), args); }
            catch { return T(key); }
        }

        public static string[] A(string key)
        {
            if (_arrays.TryGetValue(key, out var pair))
                return Current == EN ? pair.en : pair.pl;
            return Array.Empty<string>();
        }

